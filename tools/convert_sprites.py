"""Convert the Higgsfield PNGs in ../sprites_src into RGB565 data (sprites.h + sprites.cpp).

Dog sprites are chroma-keyed off the green background, scaled, and cropped. Frames of the same
animation (walk, run, eat) share one crop box so the cycle doesn't jitter. Transparent pixels are
set to KEY (pure green, 0x07E0). The room image is scaled/cropped to the scene area.

Pixel data is emitted as string literals rather than {0x1234, ...} initialisers: GCC parses a few
MB of string in seconds, while 400k-element initialiser lists take ~10 minutes.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "sprites_src"
OUT_H = ROOT / "sprites.h"
OUT_C = ROOT / "sprites.cpp"

DOG_SCALE = 230 / 1024  # 1024px source -> ~200px tall sitting dog
SCENE_W, SCENE_H = 368, 280
KEY = 0x07E0
# groups of frames that share a crop box
GROUPS = [
    ["idle"], ["blink"], ["happy"], ["bark"], ["sad"], ["dizzy"], ["bath"], ["sleep"],
    ["eat", "eat2"],
    ["walk1", "walk2", "walk3"],
    ["run1", "run2"],
]


def rgb565(r, g, b):
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return 0x07C0 if v == KEY else v  # never collide with the key colour


def key_dog(path):
    im = Image.open(path).convert("RGB")
    im = im.resize((round(im.width * DOG_SCALE), round(im.height * DOG_SCALE)), Image.LANCZOS)
    w, h = im.size
    px = im.load()
    alpha = Image.new("L", (w, h), 0)
    ap = alpha.load()
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            spill = g - max(r, b)
            if spill > 70:
                continue  # background
            if spill > 0:  # despill edge pixels
                px[x, y] = (r, max(r, b), b)
            ap[x, y] = 255
    return im, alpha


def emit(name, w, h, data, fh, fc):
    up = name.upper()
    fh.write(f"static const uint16_t SPR_{up}_W = {w}, SPR_{up}_H = {h};\n")
    fh.write(f"extern const uint8_t spr_{name}_bytes[];\n")
    fh.write(f"#define spr_{name} ((const uint16_t *)spr_{name}_bytes)\n\n")
    raw = b"".join(v.to_bytes(2, "little") for v in data)
    fc.write(f"alignas(4) const uint8_t spr_{name}_bytes[{len(raw) + 1}] =\n")
    for i in range(0, len(raw), 64):
        fc.write('  "' + "".join(f"\\x{b:02x}" for b in raw[i:i + 64]) + '"\n')
    fc.write(";\n\n")


def main():
    with open(OUT_H, "w") as fh, open(OUT_C, "w") as fc:
        fh.write("// Generated by tools/convert_sprites.py from Higgsfield images. Do not edit.\n")
        fh.write("#pragma once\n#include <stdint.h>\n\n")
        fh.write(f"#define SPR_KEY 0x{KEY:04X}\n\n")
        fc.write("// Generated by tools/convert_sprites.py from Higgsfield images. Do not edit.\n")
        fc.write('#include "sprites.h"\n\n')

        for group in GROUPS:
            frames = [key_dog(SRC / f"{n}.png") for n in group]
            box = frames[0][1].getbbox()
            for _, a in frames[1:]:
                b = a.getbbox()
                box = (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
            for n, (im, a) in zip(group, frames):
                im, a = im.crop(box), a.crop(box)
                p, ap = im.load(), a.load()
                data = [rgb565(*p[x, y]) if ap[x, y] else KEY for y in range(im.height) for x in range(im.width)]
                emit(n, im.width, im.height, data, fh, fc)
                print(f"{n}: {im.width}x{im.height}")

        room = Image.open(SRC / "room.png").convert("RGB")
        s = max(SCENE_W / room.width, SCENE_H / room.height)
        room = room.resize((round(room.width * s), round(room.height * s)), Image.LANCZOS)
        l, t = (room.width - SCENE_W) // 2, (room.height - SCENE_H) // 2
        room = room.crop((l, t, l + SCENE_W, t + SCENE_H))
        rp = room.load()
        emit("room", SCENE_W, SCENE_H, [rgb565(*rp[x, y]) for y in range(SCENE_H) for x in range(SCENE_W)], fh, fc)
    print("wrote", OUT_H, "and", OUT_C)


if __name__ == "__main__":
    sys.exit(main())
